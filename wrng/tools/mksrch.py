#!/usr/bin/env python3
"""mksrch.py - index of the record tables searched by the arcade at 0xA07A (src/glue.s srch_hook).

Usage: mksrch.py <wr_cpu.bin> <out srch_idx.inc>

The loop at 0xA07A looks for the record whose first word equals d0 in one of four tables (records of
words ended by $00FF), one compare per record.  The index holds, per table and key 0..63, the address
of the first record with that key (0 = not in the first records: the hook falls back to the loop).
The tables are not encrypted, so the program ROM as dumped is the source.
"""
import struct
import sys

TABLES = (0xE15B2, 0xE1A12, 0xE1382, 0xE17E2)


def main(argv):
    cpu = open(argv[1], 'rb').read()
    w = lambda a: struct.unpack('>H', cpu[a:a + 2])[0]
    out = ['* generated by tools/mksrch.py - first record per key (0..63) of the tables searched at 0xA07A']
    for t in TABLES:
        idx = [0] * 64
        pos = t
        for _ in range(400):
            k = w(pos)
            if k < 64 and not idx[k]:
                idx[k] = pos
            pos += 2
            while w(pos) != 0xFF:
                pos += 2
            pos += 2
            if pos - t > 0x1800:
                break
        out.append('        .long   ' + ','.join('0x%X' % v for v in idx))
    open(argv[2], 'w').write('\n'.join(out) + '\n')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
