def tile_from_bitmap(rows, pen=1):
    """rows: list of up to 8 strings of '0'/'1' (5 wide), returns 8x8 pen matrix"""
    m = [[0] * 8 for _ in range(8)]
    for y, r in enumerate(rows[:8]):
        for x, c in enumerate(r[:8]):
            if c == '1':
                m[y][x + 1] = pen
    return m


def encode_tile(m):
    out = bytearray(32)
    for blk, (x0) in enumerate((4, 6, 0, 2)):
        for y in range(8):
            out[blk * 8 + y] = (m[y][x0] & 0xF) | ((m[y][x0 + 1] & 0xF) << 4)
    return bytes(out)


def main():
    rom = bytearray(0x20000)
    blank = encode_tile([[0] * 8 for _ in range(8)])
    for i in range(0x1000):
        rom[i * 32:(i + 1) * 32] = blank
    for ch, rows in FONT.items():
        i = ord(ch)
        rom[i * 32:(i + 1) * 32] = encode_tile(tile_from_bitmap(rows))
    # lowercase = uppercase
    for c in range(ord('a'), ord('z') + 1):
        rom[c * 32:(c + 1) * 32] = rom[(c - 32) * 32:(c - 32 + 1) * 32]
    open(sys.argv[1], 'wb').write(rom)


if __name__ == '__main__':
    main()
