| Transformation (human -> dolphin) inside the game's own intro.
| The intro's frame loop turns the display on at ROM 0xC572 right after sending its
| sprite list; that instruction becomes a call to intro_hook. When the intro first
| shows the Rynex (sprite 2 is a 4x4 sprite using tile 0x1D0/0x1E0) the sequence plays
| as sprites over the intro, with the intro waiting; the music runs on the Z80 and
| goes on. Afterwards palette line 3 is restored and the intro carries on.
| Assemble: m68k-linux-gnu-as -m68000 --register-prefix-optional
| Step table and graphics come from intro_data.s (generated by build_patch.py).

        .equ    VDP_DATA, 0xC00000
        .equ    VDP_CTRL, 0xC00004
        .equ    PAD1_DATA, 0xA10003
        .equ    DONE, 0xFFF0C0          | word; RAM only cleared at power-on, unused by the game
        .equ    MAGIC, 0x4443
        .equ    SPRBUF, 0xFFEC00        | intro's sprite list (DMA'd to the SAT at 0xF800)
        .equ    FRAMES, 0xFF8C80        | intro frame counter
        .equ    BANK0, 792              | free VRAM tiles during the intro
        .equ    BANK1, 1026
        .equ    X0, 128 + 80            | top-left of the 160x160 picture
        .equ    Y0, 128 + 32

| step record (see intro_data.s)
        .equ    S_SET, 0                | .l set: .w tiles, .w sprites, tiles, then (y, x, tile) words
        .equ    S_PAL, 4                | .l 16 CRAM words
        .equ    S_TICKS, 8              | .w frames on screen
        .equ    S_SIZE, 10

        .text
        .globl  intro_hook
intro_hook:
        move.w  #0x8144, VDP_CTRL       | the instruction replaced by the call: display on
        movem.l d0-d7/a0-a6, -(sp)
        cmpi.w  #0x80, FRAMES           | early in the intro: arm for this run
        bcc.s   1f
        clr.w   DONE
        bra.s   9f
1:      cmpi.w  #MAGIC, DONE
        beq.s   9f
        move.b  SPRBUF+0x12, d0         | sprite 2: size 4x4 ...
        andi.b  #0x0F, d0
        cmpi.b  #0x0F, d0
        bne.s   9f
        move.w  SPRBUF+0x14, d0         | ... showing the Rynex
        andi.w  #0x7FF, d0
        cmpi.w  #0x1D0, d0
        beq.s   2f
        cmpi.w  #0x1E0, d0
        bne.s   9f
2:      move.w  #MAGIC, DONE
        bsr.s   transform
9:      movem.l (sp)+, d0-d7/a0-a6
        rts

transform:
        lea     VDP_CTRL, a5
        lea     VDP_DATA, a6
        tst.w   (a5)
        move.w  #0x8F02, (a5)
        lea     -32(sp), sp             | keep palette line 3
        movea.l sp, a3
        move.l  #0x00600020, (a5)       | CRAM read 0x60
        moveq   #15, d7
1:      move.w  (a6), (a3)+
        dbra    d7, 1b

        lea     intro_steps, a4
        moveq   #0, d5                  | set currently in VRAM
        move.w  #BANK1, d6              | bank of that set (first load goes to BANK0)

step:   move.l  S_SET(a4), d0
        beq.w   done
        cmp.l   d0, d5
        beq.s   same_set
        move.l  d0, d5                  | load into the bank not on screen
        movea.l d0, a0
        move.l  #0x63000001, d1             | VRAM write, tile BANK0
        move.w  #BANK0, d2
        cmpi.w  #BANK0, d6
        bne.s   2f
        move.l  #0x40400002, d1             | VRAM write, tile BANK1
        move.w  #BANK1, d2
2:      move.w  d2, d6
        move.l  d1, (a5)
        move.w  (a0)+, d7
        addq.l  #2, a0
        lsl.w   #3, d7                  | 8 longs per tile
        subq.w  #1, d7
3:      move.l  (a0)+, (a6)
        dbra    d7, 3b
same_set:
        bsr.w   wait_vblank
        move.l  #0xC0600000, (a5)       | palette line 3
        movea.l S_PAL(a4), a0
        moveq   #15, d7
4:      move.w  (a0)+, (a6)
        dbra    d7, 4b

        movea.l d5, a0                  | sprite list straight into the SAT (0xF800)
        move.w  (a0)+, d0
        move.w  (a0)+, d3
        lsl.w   #5, d0                  | skip the tiles
        adda.w  d0, a0
        move.l  #0x78000003, (a5)
        moveq   #1, d2                  | link
        subq.w  #1, d3
5:      move.w  (a0)+, (a6)             | y
        move.w  d2, d0
        cmp.w   d3, d2
        bls.s   6f
        moveq   #0, d0                  | last sprite ends the list
6:      ori.w   #0x0500, d0             | 2x2
        move.w  d0, (a6)
        move.w  (a0)+, d1               | x
        move.w  (a0)+, d0
        add.w   d6, d0
        ori.w   #0xE000, d0             | priority, palette 3
        move.w  d0, (a6)
        move.w  d1, (a6)
        addq.w  #1, d2
        dbra    d3, 5b

        move.w  S_TICKS(a4), d4
        subq.w  #1, d4
        ble.s   8f
7:      bsr.w   wait_vblank
        bsr.w   start_pressed
        bne.s   done
        subq.w  #1, d4
        bne.s   7b
8:      lea     S_SIZE(a4), a4
        bra.w   step

done:   bsr.w   wait_vblank
        move.l  #0x78000003, (a5)       | hide our sprites until the game's next SAT update
        moveq   #0, d0
        move.l  d0, (a6)
        move.l  d0, (a6)
        move.l  #0xC0600000, (a5)       | palette line 3 back
        movea.l sp, a3
        moveq   #15, d7
1:      move.w  (a3)+, (a6)
        dbra    d7, 1b
        lea     32(sp), sp
        rts

wait_vblank:                            | wait for the start of the next VBlank
1:      move.w  (a5), d0
        btst    #3, d0
        bne.s   1b
2:      move.w  (a5), d0
        btst    #3, d0
        beq.s   2b
        rts

start_pressed:                          | Z clear when Start is held on pad 1
        move.b  PAD1_DATA, d1
        move.b  #0x00, PAD1_DATA
        nop
        nop
        move.b  PAD1_DATA, d0
        move.b  d1, PAD1_DATA
        not.b   d0
        andi.b  #0x20, d0
        rts
        .even
