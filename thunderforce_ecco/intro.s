| Intro: the human turns into the dolphin, shown before Lightening Force boots.
| Runs from the reset vector with interrupts off, polls VBlank, then jumps to the
| game's own reset code (ORIG_RESET), which reinitialises the hardware.
| Assemble: m68k-linux-gnu-as -m68000 --register-prefix-optional
| Step table and graphics come from intro_data.s (generated by build_patch.py).

        .equ    VDP_DATA, 0xC00000
        .equ    VDP_CTRL, 0xC00004
        .equ    PAD1_DATA, 0xA10003
        .equ    PAD1_CTRL, 0xA10009

| step record (see intro_data.s)
        .equ    S_TILES, 0              | .l tiles, 0 ends the table
        .equ    S_NTILES, 4             | .w tile count
        .equ    S_MAP, 6                | .l map: cols*rows words, 0 = empty, n = nth tile
        .equ    S_COLS, 10              | .w
        .equ    S_ROWS, 12              | .w
        .equ    S_PAL, 14               | .l 16 CRAM words
        .equ    S_TICKS, 18             | .w frames on screen
        .equ    S_NTADDR, 20            | .w VRAM address of the top-left cell (plane A)
        .equ    S_SIZE, 22

        .text
        .globl  intro
intro:
        move.w  #0x2700, sr
        move.b  0xA10001, d0            | TMSS
        andi.b  #0x0F, d0
        beq.s   1f
        move.l  #0x53454741, 0xA14000
1:      lea     VDP_CTRL, a5
        lea     VDP_DATA, a6
        tst.w   (a5)
        lea     vdpregs(pc), a0
        moveq   #(vdpregs_end - vdpregs) / 2 - 1, d7
2:      move.w  (a0)+, (a5)
        dbra    d7, 2b

        moveq   #0, d0
        move.l  #0x40000000, (a5)       | clear VRAM
        move.w  #0x3FFF, d7
3:      move.l  d0, (a6)
        dbra    d7, 3b
        move.l  #0xC0000000, (a5)       | clear CRAM
        moveq   #31, d7
4:      move.l  d0, (a6)
        dbra    d7, 4b
        move.l  #0x40000010, (a5)       | clear VSRAM
        moveq   #19, d7
5:      move.l  d0, (a6)
        dbra    d7, 5b

        move.b  #0x40, PAD1_CTRL        | TH as output, for the Start button
        move.b  #0x40, PAD1_DATA
        move.w  #0x8144, (a5)           | display on

        lea     intro_steps, a4
        moveq   #0, d5                  | tiles currently in VRAM
        move.w  #512, d6                | bank of those tiles (first load flips to 1)

step:   move.l  S_TILES(a4), d0
        beq.w   done
        cmp.l   d0, d5
        beq.s   same_tiles
        move.l  d0, d5                  | load into the bank not on screen
        movea.l d0, a0
        move.l  #0x40200000, d1         | bank 1 -> tile 1 (VRAM 0x0020)
        move.w  #1, d2
        cmpi.w  #1, d6
        bne.s   6f
        move.l  #0x40000001, d1         | bank 512 -> VRAM 0x4000
        move.w  #512, d2
6:      move.w  d2, d6
        move.l  d1, (a5)
        move.w  S_NTILES(a4), d7
        lsl.w   #3, d7                  | 8 longs per tile
        subq.w  #1, d7
7:      move.l  (a0)+, (a6)
        dbra    d7, 7b
same_tiles:
        bsr.w   wait_vblank
        move.l  #0xC0000000, (a5)       | palette line 0
        movea.l S_PAL(a4), a0
        moveq   #15, d7
8:      move.w  (a0)+, (a6)
        dbra    d7, 8b

        movea.l S_MAP(a4), a0           | name table, row by row
        move.w  S_NTADDR(a4), d2
        move.w  S_ROWS(a4), d3
        subq.w  #1, d3
9:      moveq   #0, d1                  | VRAM write command for address d2
        move.w  d2, d1
        andi.w  #0x3FFF, d1
        ori.w   #0x4000, d1
        swap    d1
        move.w  d2, d1
        rol.w   #2, d1
        andi.w  #3, d1
        move.l  d1, (a5)
        move.w  S_COLS(a4), d7
        subq.w  #1, d7
10:     move.w  (a0)+, d0
        beq.s   11f
        add.w   d6, d0
        subq.w  #1, d0
11:     move.w  d0, (a6)
        dbra    d7, 10b
        addi.w  #128, d2                | 64 cells per plane row
        dbra    d3, 9b

        move.w  S_TICKS(a4), d4
        subq.w  #1, d4
        ble.s   13f
12:     bsr.w   wait_vblank
        bsr.w   start_pressed
        bne.s   done
        subq.w  #1, d4
        bne.s   12b
13:     lea     S_SIZE(a4), a4
        bra.w   step

done:   move.w  #0x8104, (a5)           | display off
        move.b  #0x00, PAD1_CTRL        | leave the port as at power-on: the game's
        move.b  #0x00, PAD1_DATA        | init treats a set port as a soft reset
        jmp     ORIG_RESET

wait_vblank:                            | wait for the start of the next VBlank
1:      move.w  (a5), d0
        btst    #3, d0
        bne.s   1b
2:      move.w  (a5), d0
        btst    #3, d0
        beq.s   2b
        rts

start_pressed:                          | Z clear when Start is held on pad 1
        move.b  #0x00, PAD1_DATA
        nop
        nop
        move.b  PAD1_DATA, d0
        move.b  #0x40, PAD1_DATA
        not.b   d0
        andi.b  #0x20, d0
        rts

vdpregs:
        .word   0x8004, 0x8104, 0x8230, 0x8334, 0x8407, 0x8578, 0x8600, 0x8700
        .word   0x8800, 0x8900, 0x8AFF, 0x8B00, 0x8C81, 0x8D3F, 0x8E00, 0x8F02
        .word   0x9001, 0x9100, 0x9200
vdpregs_end:
        .even
