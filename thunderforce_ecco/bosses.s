| New final bosses for stages 1 to 4 (see bosses.py).
| The game's sprite-list builder (ROM 0x7138) ends with 'clr.b -5(a0); rts' at 0x7190,
| a0 pointing past the last sprite of the list at 0xFF9C00; that becomes 'jmp boss_hook'.
| During a boss fight the hook takes the boss's pieces out of the list, turns its
| projectiles into the character's projectile, appends the character's frame anchored to
| one boss piece, relinks the list and sets the character's palette line in the game's
| palette buffer (0xFF9F00, sent to CRAM every frame).
| Bosses whose frames do not fit in the stage's tile bank (Bart) keep them in ROM: the
| frame to show is copied to one of two VRAM slots by DMA, in two halves on two frames
| (boss_vblank, called from the game's per-frame DMA code at 0x1DBE), and shown once
| it is complete.
| Assemble: m68k-linux-gnu-as -m68000 --register-prefix-optional
| Boss data (boss0 ... boss3) comes from bosses_data.s (generated by build_patch.py).

        .equ    SPRITES, 0xFF9C00       | sprite list, 80 entries of 8 bytes
        .equ    OBJECTS, 0xFF8818       | 40 objects of 0x60 bytes: +2 routine, +4 energy
        .equ    STAGE, 0xFFF0B8
        .equ    BANK_LOAD, 0xFFF30E     | boss bank: 0x80 before loading, 0 once in VRAM
        .equ    PALBUF, 0xFF9F00        | palette buffer sent to CRAM
        .equ    VRAM_DMA, 0x1AD8        | game's DMA: d0 source/2, d1 VRAM address, d2 words
        .equ    AX, 0xFFF0C2            | last anchor x, y, priority bit (RAM unused by the game)
        .equ    AY, 0xFFF0C4
        .equ    APRI, 0xFFF0C6
        .equ    ENERGY, 0xFFF0C8        | .l boss energy last frame
        .equ    TICK, 0xFFF0CC
        .equ    HIT, 0xFFF0CE           | hit flash (20-17) and its cooldown
        .equ    ATTACK, 0xFFF0D0        | frames of attack pose left
        .equ    SEEN, 0xFFF0D2          | stage + 1 once its boss has been seen
        .equ    GONE, 0xFFF0D4          | frames left after the boss objects are gone
        .equ    SHOWN, 0xFFF0D6         | DMA bosses: frame in the front slot (0xFFFF none)
        .equ    LOADING, 0xFFF0D8       | frame being copied to the back slot
        .equ    STEP, 0xFFF0DA          | halves of it still to queue
        .equ    SLOT, 0xFFF0DC          | front slot, 0 or 2
        .equ    DMAPEND, 0xFFF0DE       | DMA request for boss_vblank: flag, source, VRAM, words
        .equ    DMASRC, 0xFFF0E0
        .equ    DMADST, 0xFFF0E4
        .equ    DMALEN, 0xFFF0E6

| boss record (see bosses.py)
        .equ    B_ANCHOR, 0             | 4 .w anchor tiles (0xFFFF = none)
        .equ    B_ADX, 8                | .w, .w anchor -> top left of the character
        .equ    B_ADY, 10
        .equ    B_RMLO, 12              | .w, .w tiles of the pieces to take out
        .equ    B_RMHI, 14
        .equ    B_PJLO, 16              | .w, .w tiles of the projectiles
        .equ    B_PJHI, 18
        .equ    B_PJT, 20               | .w projectile tile (2x2)
        .equ    B_PJD, 22               | .w offset of the projectile (x)
        .equ    B_FRAMES, 24            | .l frame table: 0 base, 1 attack, 2 defeat, then idle frames
        .equ    B_PALS, 28              | .l normal, brillo2, golpe, derrota (16 words each)
        .equ    B_IDLE, 32              | .l idle steps: .w frame, palette, ticks
        .equ    B_IDLELEN, 36           | .w total ticks of the idle steps
        .equ    B_LINE, 38              | .w palette line of the boss and character, as attribute bits
        .equ    B_PALOFS, 40            | .w the same line's offset in PALBUF
        .equ    B_PJDY, 42              | .w offset of the projectile (y)
        .equ    B_PJVF, 44              | .w 1: vertically flipped projectile pieces are halves, drop them
        .equ    B_SPIN, 46              | .l 4 flip words for the projectile, 4 ticks each
        .equ    B_DMA, 50               | .l per frame: .l ROM address, .w words (0: frames in the bank)
        .equ    B_SLOTS, 54             | .w, .w first tile of the two VRAM slots

        .text
        .globl  boss_hook, boss_vblank
boss_hook:
        movem.l d0-d7/a1-a6, -(sp)
        move.l  a0, d0                  | the game's a0 is sign-extended (0xFFFF9xxx)
        andi.l  #0x00FFFFFF, d0
        movea.l d0, a0
        move.w  STAGE, d0
        cmpi.w  #3, d0
        bhi.w   done
        tst.w   BANK_LOAD
        beq.s   0f
        clr.w   SEEN                    | a boss bank is loading: a new fight
        bra.w   done
0:      lsl.w   #2, d0
        lea     boss_table(pc), a4
        movea.l (a4, d0.w), a4

        lea     OBJECTS, a1             | boss objects: any? energy left?
        moveq   #39, d7
        moveq   #0, d5                  | found
        moveq   #0, d6                  | total energy
1:      cmpi.w  #0x30, 2(a1)
        bne.s   2f
        moveq   #1, d5
        moveq   #0, d0
        move.w  4(a1), d0
        bmi.s   2f                      | negative: destroyed
        add.l   d0, d6
2:      lea     0x60(a1), a1
        dbra    d7, 1b
        tst.w   d5
        bne.s   11f
        move.w  STAGE, d0               | no boss objects: after its death the wreck keeps
        addq.w  #1, d0                  | using the bank's tiles; keep taking it out and let
        cmp.w   SEEN, d0                | the character sink in the defeat pose
        bne.w   done
        subq.w  #1, GONE
        bne.s   12f
        clr.w   SEEN
        bra.w   done
12:     clr.l   ENERGY
        addq.w  #1, AY
        addq.w  #1, TICK
        moveq   #4, d5                  | bit 2: gone, the anchor is not looked for
        bra.s   13f
11:     move.w  STAGE, d0
        addq.w  #1, d0
        cmp.w   SEEN, d0
        beq.s   14f
        move.w  d0, SEEN                | new fight: no anchor position yet, slots empty
        move.w  #0x7FFF, AY
        moveq   #-1, d0
        move.w  d0, SHOWN
        move.w  d0, LOADING
        clr.w   STEP
        clr.w   SLOT
        clr.w   DMAPEND
        clr.w   HIT
        clr.w   ATTACK
        move.l  d6, ENERGY
14:     move.w  #300, GONE

        addq.w  #1, TICK
        cmp.l   ENERGY, d6              | energy dropped: hit flash (4 frames, then 16 without)
        bcc.s   3f
        tst.w   HIT
        bne.s   3f
        move.w  #20, HIT
3:      move.l  d6, ENERGY

| take the pieces out, convert the projectiles, find the anchor
        moveq   #0, d5                  | bit 0: anchor found, bit 1: projectile seen
13:     lea     SPRITES, a2             | read
        movea.l a2, a3                  | write
4:      cmpa.l  a0, a2
        bcc.w   7f
        move.w  4(a2), d0
        move.w  d0, d1
        andi.w  #0x7FF, d1
        move.w  d0, d2
        andi.w  #0x6000, d2
        cmp.w   B_LINE(a4), d2          | anchor: the boss's palette line, not flipped vertically
        bne.s   5f
        btst    #2, d5
        bne.s   5f
        btst    #12, d0
        bne.s   5f
        lea     B_ANCHOR(a4), a5
        moveq   #3, d3
41:     cmp.w   (a5)+, d1
        dbeq    d3, 41b
        bne.s   5f
        bset    #0, d5
        move.w  6(a2), AX
        move.w  (a2), AY
        andi.w  #0x8000, d0
        move.w  d0, APRI
        move.w  4(a2), d0
5:      cmp.w   B_RMLO(a4), d1          | boss piece, any palette: drop it
        bcs.s   51f
        cmp.w   B_RMHI(a4), d1
        bls.w   65f
51:     cmp.w   B_LINE(a4), d2
        bne.s   6f
        cmp.w   B_PJLO(a4), d1
        bcs.s   6f
        cmp.w   B_PJHI(a4), d1
        bhi.s   6f
        bset    #1, d5                  | projectile -> 2x2, spinning
        tst.w   B_PJVF(a4)
        beq.s   52f
        btst    #12, d0
        bne.s   65f
52:     move.w  (a2), d3
        add.w   B_PJDY(a4), d3
        move.w  d3, (a3)+
        move.b  #0x05, (a3)+
        move.b  3(a2), (a3)+
        andi.w  #0x8000, d0
        or.w    B_LINE(a4), d0
        or.w    B_PJT(a4), d0
        move.w  TICK, d3
        lsr.w   #2, d3
        andi.w  #3, d3
        add.w   d3, d3
        movea.l B_SPIN(a4), a5
        or.w    (a5, d3.w), d0
        move.w  d0, (a3)+
        move.w  6(a2), d3
        add.w   B_PJD(a4), d3
        move.w  d3, (a3)+
        bra.s   65f
6:      move.l  (a2), (a3)+
        move.l  4(a2), (a3)+
65:     addq.l  #8, a2
        bra.w   4b
7:      movea.l a3, a0

| pick frame (d3) and palette (d4)
        btst    #1, d5                  | projectiles out: attack pose
        beq.s   71f
        move.w  #24, ATTACK
71:     tst.l   ENERGY                  | no energy left, or no anchor (the boss is breaking
        beq.s   72f                     | up): defeat pose where it was last seen, sinking
        btst    #0, d5
        bne.s   76f
72:     cmpi.w  #0x1C0, AY
        bhi.w   relink
        moveq   #2, d3
        moveq   #3, d4
        btst    #4, TICK+1
        beq.w   8f
        moveq   #0, d4
        bra.w   8f
76:     tst.w   ATTACK
        beq.s   74f
        subq.w  #1, ATTACK
        moveq   #1, d3
        moveq   #0, d4
        btst    #2, TICK+1
        beq.s   77f
        moveq   #1, d4
        bra.s   77f
74:     moveq   #0, d0                  | idle steps
        move.w  TICK, d0
        divu    B_IDLELEN(a4), d0
        swap    d0
        movea.l B_IDLE(a4), a5
75:     move.w  (a5)+, d3
        move.w  (a5)+, d4
        sub.w   (a5)+, d0
        bcc.s   75b
77:     tst.w   HIT                     | hit: same pose, flash palette
        beq.s   8f
        subq.w  #1, HIT
        cmpi.w  #16, HIT
        bcs.s   8f
        moveq   #2, d4

8:      lsl.w   #5, d4                  | palette line
        movea.l B_PALS(a4), a5
        adda.w  d4, a5
        lea     PALBUF, a6
        adda.w  B_PALOFS(a4), a6
        moveq   #7, d1
81:     move.l  (a5)+, (a6)+
        dbra    d1, 81b

        moveq   #0, d5                  | first tile of the frame's tiles
        tst.l   B_DMA(a4)
        beq.s   85f
        bsr.w   dma_frame
        tst.w   d3
        bmi.w   relink

85:     lsl.w   #2, d3                  | append the frame
        movea.l B_FRAMES(a4), a5
        movea.l (a5, d3.w), a5
        move.w  (a5)+, d7
        subq.w  #1, d7
        move.w  AX, d1
        add.w   B_ADX(a4), d1
        move.w  AY, d2
        add.w   B_ADY(a4), d2
        move.w  APRI, d3
        or.w    B_LINE(a4), d3
        lea     SPRITES + 80*8, a6
9:      cmpa.l  a6, a0
        bcc.s   relink
        move.w  (a5)+, d4               | dx
        move.w  (a5)+, d0               | dy
        add.w   d2, d0
        andi.w  #0x3FF, d0
        move.w  d0, (a0)+
        move.w  (a5)+, d0               | size; link set below
        lsl.w   #8, d0
        move.w  d0, (a0)+
        move.w  (a5)+, d0               | tile
        add.w   d5, d0
        or.w    d3, d0
        move.w  d0, (a0)+
        add.w   d1, d4
        andi.w  #0x1FF, d4
        bne.s   91f
        moveq   #1, d4                  | x = 0 would mask the sprites behind
91:     move.w  d4, (a0)+
        dbra    d7, 9b

relink: lea     SPRITES, a2             | links 1, 2, 3 ... (the end is cleared below)
        moveq   #1, d0
10:     cmpa.l  a0, a2
        bcc.s   done
        move.b  d0, 3(a2)
        addq.b  #1, d0
        addq.l  #8, a2
        bra.s   10b

done:   movem.l (sp)+, d0-d7/a1-a6
        clr.b   -5(a0)                  | the instructions replaced by the jump
        rts

| DMA bosses: d3 = frame wanted. Returns d3 = frame to draw (the one in the front slot,
| -1 if none yet) and d5 = first tile of the front slot. Uses d0-d2, a5.
dma_frame:
        cmp.w   SHOWN, d3
        beq.w   9f
        tst.w   DMAPEND                 | last half not copied yet
        bne.w   9f
        cmp.w   LOADING, d3
        beq.s   2f
        move.w  d3, LOADING             | start copying it: first half
        move.w  #2, STEP
2:      tst.w   STEP
        bne.s   3f
        move.w  d3, SHOWN               | both halves copied: swap the slots
        eori.w  #2, SLOT
        bra.w   9f
3:      movea.l B_DMA(a4), a5           | queue the next half to the back slot
        move.w  d3, d0
        mulu    #6, d0
        adda.w  d0, a5
        move.w  4(a5), d2               | words of the frame; a half is d2/2
        lsr.w   #1, d2
        moveq   #0, d1
        cmpi.w  #1, STEP
        bne.s   4f
        move.w  d2, d1                  | second half: + d2 words
        add.w   d1, d1
4:      move.l  (a5), d0
        add.l   d1, d0
        move.l  d0, DMASRC
        move.w  SLOT, d0
        eori.w  #2, d0
        move.w  B_SLOTS(a4, d0.w), d0
        lsl.w   #5, d0
        add.w   d1, d0
        move.w  d0, DMADST
        move.w  d2, DMALEN
        move.w  #1, DMAPEND
        subq.w  #1, STEP
9:      move.w  SHOWN, d3
        move.w  SLOT, d0
        move.w  B_SLOTS(a4, d0.w), d5
        rts

| Called from the game's per-frame DMA code (ROM 0x1DBE, instead of its first
| instruction 'move.l #0x7FCE00, d0').
boss_vblank:
        tst.w   DMAPEND
        beq.s   1f
        movem.l d3/a0, -(sp)
        clr.w   DMAPEND
        move.l  DMASRC, d0
        lsr.l   #1, d0
        move.w  DMADST, d1
        move.w  DMALEN, d2
        jsr     VRAM_DMA
        movem.l (sp)+, d3/a0
1:      move.l  #0x7FCE00, d0
        rts

boss_table:
        .long   boss0, boss1, boss2, boss3
        .even
